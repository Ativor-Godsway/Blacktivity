/**
 * STAMPS THE STYLESHEET WITH A CONTENT HASH — Revision 23 §2.
 *
 * Writes the same value into two places:
 *
 *   app/globals.css      :root { --stylesheet-build: "<hash>" }
 *   lib/stylesheet-build.ts   export const STYLESHEET_BUILD = "<hash>"
 *
 * The first travels to the browser inside the stylesheet; the second is
 * rendered into the HTML. If a browser is using a stylesheet from an older
 * build, the two disagree, and `StylesheetGuard` says so out loud instead of
 * letting the page render wrong.
 *
 * ONE SCRIPT WRITES BOTH, so they cannot drift. A second implementation of the
 * same hash on the server would be a new way for this to give a false answer.
 *
 * The hash is taken over the file with its own stamp line removed, so stamping
 * twice in a row is idempotent and does not churn the file on every build.
 *
 *   node scripts/build/stamp-stylesheet.mjs
 *   node scripts/build/stamp-stylesheet.mjs --check   (verify, do not write)
 */
import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";

const CSS = "app/globals.css";
const TS = "lib/stylesheet-build.ts";
const CHECK = process.argv.includes("--check");

const STAMP_RE = /^\s*--stylesheet-build:\s*"[^"]*";\s*\n/m;

const raw = readFileSync(CSS, "utf8");
const withoutStamp = raw.replace(STAMP_RE, "");
const hash = createHash("sha256").update(withoutStamp).digest("hex").slice(0, 12);

/*
 * The stamp goes in the first `:root` block. `@theme` is Tailwind's and is
 * rewritten at build time; `:root` is ours and is emitted verbatim.
 */
const ROOT = ":root {\n";
if (!withoutStamp.includes(ROOT)) {
  console.error(`STAMP FAILED: no \`${ROOT.trim()}\` block in ${CSS}`);
  process.exit(1);
}

const stampLine =
  `  /* Written by scripts/build/stamp-stylesheet.mjs — Revision 23 §2.\n` +
  `     A content hash of this file, compared in development against the same\n` +
  `     value rendered into the HTML. They disagree only when the browser is\n` +
  `     using a stylesheet from an older build. */\n` +
  `  --stylesheet-build: "${hash}";\n`;

// Drop any previous stamp and its comment, then insert the new one.
const cleaned = withoutStamp.replace(
  /\n  \/\* Written by scripts\/build\/stamp-stylesheet\.mjs[\s\S]*?\*\/\n/,
  "\n",
);
const i = cleaned.indexOf(ROOT) + ROOT.length;
const nextCss = cleaned.slice(0, i) + stampLine + cleaned.slice(i);

const nextTs = `/**
 * GENERATED by \`node scripts/build/stamp-stylesheet.mjs\` — do not edit.
 *
 * A content hash of app/globals.css. The same value is written into the
 * stylesheet as \`--stylesheet-build\`; \`StylesheetGuard\` compares the two in
 * development and complains loudly when a browser is rendering fresh HTML
 * against a stale stylesheet. See Revision 23 §2.
 */
export const STYLESHEET_BUILD = "${hash}";
`;

if (CHECK) {
  const tsNow = readFileSync(TS, "utf8");
  if (raw !== nextCss || tsNow !== nextTs) {
    console.error(
      `STYLESHEET STAMP OUT OF DATE — run \`node scripts/build/stamp-stylesheet.mjs\`.`,
    );
    process.exit(1);
  }
  console.log(`Stylesheet stamp is current — ${hash}`);
} else {
  if (raw !== nextCss) writeFileSync(CSS, nextCss);
  writeFileSync(TS, nextTs);
  console.log(`Stylesheet stamped — ${hash}`);
}
